/**
 * Writes `src/owner/confusables.ts`, the look-alike letters names are compared
 * on (F19.21), from Unicode's `confusables.txt` (UTS #39).
 *
 * Run by hand when Unicode publishes a new version, and the result committed:
 * a deployment never fetches it, and the table a name was compared on stays
 * the one in the release.
 *
 *   node scripts/confusables.ts                      # fetches the latest from unicode.org
 *   node scripts/confusables.ts path/to/confusables.txt
 *
 * Only what a person's name or handle is written in here is kept: a single
 * Latin, Cyrillic or Greek letter, or a digit, that looks like something
 * else. A letter NFKD already takes apart or folds (an e with its mark, a
 * full-width A, a mathematical bold a) is left out, since a name is taken
 * apart that way before it is mapped, as UTS #39 does: its base letter is
 * what is mapped, and the mark stays beside it. Whole scripts the owner's
 * people do not write in would make the table ten times longer and catch
 * nobody.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://www.unicode.org/Public/security/latest/confusables.txt';
const TARGET = fileURLToPath(new URL('../src/owner/confusables.ts', import.meta.url));

const given = process.argv[2];
const text = given
  ? await readFile(given, 'utf8')
  : await fetch(SOURCE).then(async (response) => {
    if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);
    return response.text();
  });

const version = /^# Version: (\S+)/m.exec(text)?.[1];
if (!version) throw new Error('that is not confusables.txt: it names no version');

const fromHex = (hex: string) => String.fromCodePoint(...hex.trim().split(/\s+/).map((one) => Number.parseInt(one, 16)));
const kept: Array<{ from: string; to: string; name: string }> = [];
for (const line of text.split('\n')) {
  const entry = /^([0-9A-F ]+);\t([0-9A-F ]+);\tMA\t#.*\)\s*(.+?)\s*→/.exec(line);
  if (!entry) continue;
  const from = fromHex(entry[1]!);
  if ([...from].length !== 1) continue;
  if (!/\p{Script=Latin}|\p{Script=Cyrillic}|\p{Script=Greek}|\p{Nd}/u.test(from)) continue;
  if (from.normalize('NFKD') !== from) continue;
  kept.push({ from, to: fromHex(entry[2]!), name: entry[3]! });
}
kept.sort((a, b) => a.from.codePointAt(0)! - b.from.codePointAt(0)!);

const escaped = (value: string) => [...value].map((char) => {
  const point = char.codePointAt(0)!;
  return point >= 0x20 && point < 0x7f && char !== "'" && char !== '\\' ? char : `\\u{${point.toString(16).toUpperCase()}}`;
}).join('');

const out = `/**
 * The look-alike letters a person's name and handle are compared on (F19.21):
 * each Latin, Cyrillic or Greek letter, or digit, that Unicode lists as
 * confusable with something else, mapped to what it looks like.
 *
 * Generated by \`scripts/confusables.ts\` from Unicode's confusables.txt
 * (UTS #39), version ${version}: ${kept.length} entries. Do not edit by hand;
 * run the script again when Unicode publishes a new version.
 */
export const CONFUSABLES: Readonly<Record<string, string>> = {
${kept.map((one) => `  '${escaped(one.from)}': '${escaped(one.to)}', // ${one.name}`).join('\n')}
};
`;
await writeFile(TARGET, out);
console.log(`${kept.length} look-alike letters from Unicode ${version} written to ${TARGET}`);
